export function getPageTitleKey(pathname: string): string | undefined {
  if (Object.hasOwn(PAGE_TITLE_KEYS, pathname)) return PAGE_TITLE_KEYS[pathname]
  if (pathname.startsWith('/pricing/')) return 'Model details'
  if (pathname.startsWith('/chat/')) return 'Chat'
  if (pathname.startsWith('/oauth/')) return 'OAuth'
  if (pathname.startsWith('/errors/')) {
    return (
      PAGE_TITLE_KEYS[`/${pathname.split('/')[2]}`] ?? 'Internal Server Error!'
    )
  }
  return undefined
}
